import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { HYPER_OPTION_DOCS } = await import(
  path.join(ROOT, 'dist', 'sdk', 'node', 'options.js')
);
const { HYPER_PRESETS } = await import(
  path.join(ROOT, 'dist', 'sdk', 'node', 'presets.js')
);

const GROUPS = [
  'Images',
  'Rasterization',
  'Fonts',
  'Structure and interactivity',
  'Metadata and cleanup',
  'Output format',
];

const fmt = (v) => (typeof v === 'boolean' ? (v ? 'true' : 'false') : String(v));
const typeCell = (d) =>
  d.type === 'number' ? `number ${d.min} to ${d.max}` : 'boolean';

let out = `---
title: Options reference
---

<!-- Generated by scripts/gen-options-doc.mjs from sdk/node/options.ts. Do not edit by hand. -->

# Options reference

Every field of \`HyperCompressOptions\`, in every surface that accepts options: the
\`options\` object in the Node and WebAssembly SDKs, \`--set key=value\` in the CLI,
and the \`options\` JSON parameter of the HTTP API. Pass any subset; unspecified
fields come from the selected preset.

This page is generated from the SDK source, so it cannot drift from the code.
`;

for (const group of GROUPS) {
  const entries = Object.entries(HYPER_OPTION_DOCS).filter(
    ([, d]) => d.group === group,
  );
  if (!entries.length) continue;
  out += `\n## ${group}\n\n`;
  if (group === 'Rasterization') {
    out += 'For image-only documents such as scans and print-to-PDF output. The engine refuses to rasterize when any page contains text, including an invisible OCR layer, so this cannot destroy searchable text; the skip is reported in the result\'s `warnings`. Rasterization is also disabled while preserving PDF/A conformance.\n\n';
  }
  out += '| Option | Type | Default | What it does |\n|---|---|---|---|\n';
  for (const [name, d] of entries) {
    out += `| \`${name}\` | ${typeCell(d)} | ${fmt(d.default)} | ${d.description} |\n`;
  }
}

out += `\n## Preset values\n
What each preset sets, field by field. A preset is just a complete options
object; start from one and override any field.\n
| Option | low | medium | high | lossless |\n|---|---|---|---|---|\n`;
for (const name of Object.keys(HYPER_OPTION_DOCS)) {
  const cells = ['low', 'medium', 'high', 'lossless']
    .map((p) => fmt(HYPER_PRESETS[p][name]))
    .join(' | ');
  out += `| \`${name}\` | ${cells} |\n`;
}

const dest = path.join(ROOT, 'docs', 'options.md');
writeFileSync(dest, out);
console.log(`wrote ${dest}`);
