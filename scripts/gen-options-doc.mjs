import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { HYPER_OPTION_DOCS } = await import(
  path.join(ROOT, 'dist', 'sdk', 'node', 'options.js')
);
const { HYPER_PRESETS } = await import(
  path.join(ROOT, 'dist', 'sdk', 'node', 'presets.js')
);

const GROUPS = [
  'Images',
  'Rasterization',
  'Fonts',
  'Structure and interactivity',
  'Metadata and cleanup',
  'Output format',
];

const fmt = (v) => (typeof v === 'boolean' ? (v ? 'true' : 'false') : String(v));
const typeCell = (d) =>
  d.type === 'number'
    ? `number ${d.min} to ${d.max}`
    : d.type === 'enum'
      ? d.values.map((v) => `\`${v}\``).join(', ')
      : 'boolean';

let out = `---
title: Options
description: Every compression option, its type, range and what each preset sets, for every surface that accepts options.
---

<!-- Generated by scripts/gen-options-doc.mjs from sdk/node/options.ts. Do not edit by hand. -->

# Options

Every option Hyper accepts. All surfaces take the same names and values. Pass only the options you want to change: everything you leave out comes from the preset (\`medium\` when you name none).

::: code-group

\`\`\`bash [CLI]
hyper input.pdf output.pdf --preset high --set grayscale=true --set imageQuality=40
\`\`\`

\`\`\`js [Node.js]
import { compress } from 'hyper-compress';

await compress({
  sourcePath: 'input.pdf',
  savePath: 'output.pdf',
  preset: 'high',
  options: { grayscale: true, imageQuality: 40 },
});
\`\`\`

\`\`\`bash [HTTP]
curl -o output.pdf --data-binary @input.pdf \\
  --url-query 'preset=high' \\
  --url-query 'options={"grayscale":true,"imageQuality":40}' \\
  'http://localhost:8080/api/compress'
\`\`\`

\`\`\`js [WebAssembly]
import { readFile, writeFile } from 'node:fs/promises';
import { compress } from 'hyper-compress-wasm';

const result = await compress(new Uint8Array(await readFile('input.pdf')), {
  preset: 'high',
  options: { grayscale: true, imageQuality: 40 },
});
await writeFile('output.pdf', result.data);
\`\`\`

:::

## How values are read

- **Numbers** outside the allowed range are clamped to the nearest end, and decimals are rounded.
- **Choices** (\`colorTarget\`, \`mrc\` and the like) fall back to their default when the value is not one of the listed ones.
- **Booleans** must be \`true\` or \`false\`; anything else falls back to the default.
- **Unknown names** are ignored, so check the spelling if a setting seems to do nothing.

A bad option never fails a run. To see exactly what will run, call \`resolveOptions\` in the [Node.js SDK](/node-sdk).

The **\`medium\`** column below is what you get when you set nothing. [Preset values](#preset-values) at the end lists all four presets. The [guides](/guides/choosing-settings) explain when to change what.
`;

for (const group of GROUPS) {
  const entries = Object.entries(HYPER_OPTION_DOCS).filter(
    ([, d]) => d.group === group,
  );
  if (!entries.length) continue;
  out += `\n## ${group}\n\n`;
  if (group === 'Rasterization') {
    out += 'For image-only documents such as scans and print-to-PDF output. Unless you also set `rasterizeText`, Hyper refuses to rasterize when any page contains text, including an invisible OCR layer, so it cannot destroy searchable text; the skip is reported as a [warning](/warnings). Rasterization is also disabled while preserving PDF/A. See [Scanned documents](/guides/scanned-documents).\n\n';
  }
  out += '| Option | Type | `medium` | What it does |\n|---|---|---|---|\n';
  for (const [name, d] of entries) {
    out += `| \`${name}\` | ${typeCell(d)} | ${fmt(HYPER_PRESETS.medium[name])} | ${d.description} |\n`;
  }
}

out += `\n## Preset values\n
What each preset sets, field by field. A preset is a complete set of options;
start from one and override any field.\n
| Option | low | medium | high | lossless |\n|---|---|---|---|---|\n`;
for (const name of Object.keys(HYPER_OPTION_DOCS)) {
  const cells = ['low', 'medium', 'high', 'lossless']
    .map((p) => fmt(HYPER_PRESETS[p][name]))
    .join(' | ');
  out += `| \`${name}\` | ${cells} |\n`;
}

const dest = path.join(ROOT, 'docs', 'options.md');
writeFileSync(dest, out);
console.log(`wrote ${dest}`);
